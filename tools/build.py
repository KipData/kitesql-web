#!/usr/bin/env python3
"""Render posts/*.md into static HTML.

The site itself is plain HTML and needs no build step to deploy; this script
is only a convenience for turning a Markdown draft into blog/<slug>.html and
refreshing index.html.

    python3 -m venv .venv && .venv/bin/pip install markdown pygments
    .venv/bin/python tools/build.py

Each post starts with a small front matter block:

    ---
    title: ...
    date: 2026-11-06
    slug: zero-copy-sql-on-lmdb
    summary: one line shown on the index
    lang: en
    ---

A translation adds `translation_of: <primary slug>` and its own `lang`; the
index lists the primary post and links to the translations next to it.
"""

from __future__ import annotations

import html
import re
from datetime import date
from pathlib import Path

import markdown
from pygments.formatters import HtmlFormatter

ROOT = Path(__file__).resolve().parent.parent
POSTS = ROOT / "posts"
BLOG = ROOT / "blog"
ASSETS = ROOT / "assets"

LANG_NAMES = {"en": "English", "zh-CN": "中文"}
SITE = "KiteSQL"
REPO = "https://github.com/KipData/KiteSQL"

HEADER = """<header class="site-header">
  <div class="wrap">
    <a class="brand" href="{root}index.html">
      <img class="logo-light" src="{root}assets/kite_sql_light.png" alt="KiteSQL">
      <img class="logo-dark" src="{root}assets/kite_sql_dark.png" alt="KiteSQL">
    </a>
    <nav class="site-nav">
      <a href="{root}index.html"{blogs_current}>Blogs</a>
      <a href="{repo}">GitHub</a>
    </nav>
  </div>
</header>
"""

FOOTER = """<footer class="site-footer">
  <div class="wrap">
    <span>© {year} KipData</span>
    <span><a href="{repo}">KiteSQL on GitHub</a></span>
  </div>
</footer>
"""

PAGE = """<!doctype html>
<html lang="{lang}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{title}</title>
  <meta name="description" content="{description}">
  <link rel="icon" type="image/jpeg" href="{root}favicon.jpeg">
  <link rel="stylesheet" href="{root}assets/style.css">
  <link rel="stylesheet" href="{root}assets/highlight.css">
</head>
<body>
{header}
<main class="wrap">
{main}
</main>
{footer}
</body>
</html>
"""


def parse_front_matter(text: str) -> tuple[dict[str, str], str]:
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise SystemExit("post is missing front matter")
    meta = {}
    for line in m.group(1).splitlines():
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip()
    return meta, text[m.end():]


def render_markdown(body: str) -> str:
    # The page template renders the title and language switch, so drop the
    # leading H1 and the "English | 中文" line used in the repository copy.
    body = re.sub(r"^# .*\n+", "", body, count=1)
    body = re.sub(r"^(?:\[?(?:English|中文)\]?(?:\([^)]*\))? \| \[?(?:English|中文)\]?(?:\([^)]*\))?)\n+", "", body, count=1)
    return markdown.markdown(
        body,
        extensions=["tables", "fenced_code", "codehilite", "sane_lists"],
        extension_configs={"codehilite": {"guess_lang": False, "css_class": "codehilite"}},
        output_format="html5",
    )


def write_highlight_css() -> None:
    light = HtmlFormatter(style="friendly").get_style_defs(".codehilite")
    dark = HtmlFormatter(style="github-dark").get_style_defs(".codehilite")
    # Drop the formatter's own background so the stylesheet's --code-bg applies.
    strip_bg = lambda css: re.sub(r"^\.codehilite \{[^}]*\}\n?", "", css, flags=re.M)
    css = (
        "/* generated by tools/build.py (pygments) */\n"
        + strip_bg(light)
        + "\n@media (prefers-color-scheme: dark) {\n"
        + "\n".join("  " + line for line in strip_bg(dark).splitlines())
        + "\n}\n"
    )
    (ASSETS / "highlight.css").write_text(css, encoding="utf-8")


def lang_switch(current: str, versions: list[tuple[str, str]], root: str) -> str:
    parts = []
    for lang, slug in versions:
        name = LANG_NAMES.get(lang, lang)
        if lang == current:
            parts.append(f"<span>{name}</span>")
        else:
            parts.append(f'<a href="{root}blog/{slug}.html">{name}</a>')
    return " · ".join(parts)


def build() -> None:
    BLOG.mkdir(exist_ok=True)
    year = date.today().year
    loaded = []
    for path in sorted(POSTS.glob("*.md")):
        meta, body = parse_front_matter(path.read_text(encoding="utf-8"))
        meta.setdefault("slug", path.stem)
        meta.setdefault("lang", "en")
        loaded.append((meta, body))

    # group translations under their primary post
    groups: dict[str, list[dict[str, str]]] = {}
    for meta, _ in loaded:
        groups.setdefault(meta.get("translation_of", meta["slug"]), []).append(meta)
    for versions in groups.values():
        versions.sort(key=lambda m: ("translation_of" in m, m["lang"]))

    for meta, body in loaded:
        versions = [(m["lang"], m["slug"]) for m in groups[meta.get("translation_of", meta["slug"])]]
        switch = lang_switch(meta["lang"], versions, "../") if len(versions) > 1 else ""
        main = (
            '<article class="post">\n'
            '  <header class="post-header">\n'
            f'    <h1>{html.escape(meta["title"])}</h1>\n'
            f'    <div class="post-meta"><time datetime="{meta["date"]}">{meta["date"]}</time>'
            + (f'<span class="sep">·</span><span class="langs">{switch}</span>' if switch else "")
            + "</div>\n  </header>\n"
            f'  <div class="post-body">\n{render_markdown(body)}\n  </div>\n'
            "</article>"
        )
        page = PAGE.format(
            lang=meta["lang"],
            title=f'{html.escape(meta["title"])} · {SITE}',
            description=html.escape(meta.get("summary", "")),
            root="../",
            header=HEADER.format(root="../", repo=REPO, blogs_current=""),
            main=main,
            footer=FOOTER.format(year=year, repo=REPO),
        )
        (BLOG / f"{meta['slug']}.html").write_text(page, encoding="utf-8")

    primaries = sorted((g[0] for g in groups.values()), key=lambda m: m["date"], reverse=True)
    items = []
    for m in primaries:
        versions = [(v["lang"], v["slug"]) for v in groups[m["slug"]]]
        langs = (
            f'<span class="sep">·</span><span class="langs">{lang_switch("", versions, "")}</span>'
            if len(versions) > 1
            else ""
        )
        items.append(
            "    <li>\n"
            f'      <div class="post-meta"><time datetime="{m["date"]}">{m["date"]}</time>{langs}</div>\n'
            f'      <h2><a href="blog/{m["slug"]}.html">{html.escape(m["title"])}</a></h2>\n'
            + (f'      <p>{html.escape(m["summary"])}</p>\n' if m.get("summary") else "")
            + "    </li>"
        )
    main = f'<h1 class="page-title">Blogs</h1>\n<ul class="post-list">\n' + "\n".join(items) + "\n</ul>"
    page = PAGE.format(
        lang="en",
        title=f"Blogs · {SITE}",
        description="Engineering notes from the KiteSQL project.",
        root="",
        header=HEADER.format(root="", repo=REPO, blogs_current=' aria-current="page"'),
        main=main,
        footer=FOOTER.format(year=year, repo=REPO),
    )
    (ROOT / "index.html").write_text(page, encoding="utf-8")
    write_highlight_css()
    print(f"built {len(loaded)} page(s), {len(primaries)} post(s)")


if __name__ == "__main__":
    build()
